import pytest

from meeting_transcript import convert_vtt_to_text, decode_transcript_upload


def test_decode_txt_returns_utf8_text_unchanged():
    text = "Sarah: Welcome everyone.\nJohn: Thanks."

    assert decode_transcript_upload("meeting.txt", text.encode("utf-8")) == text


def test_decode_accepts_case_insensitive_txt_extension():
    assert decode_transcript_upload("MEETING.TXT", b"Spoken text") == "Spoken text"


def test_decode_rejects_unsupported_extension():
    with pytest.raises(ValueError, match="Only .txt and .vtt"):
        decode_transcript_upload("meeting.pdf", b"content")


@pytest.mark.parametrize("payload", [b"", b"   \n"])
def test_decode_rejects_empty_upload(payload):
    with pytest.raises(ValueError, match="empty"):
        decode_transcript_upload("meeting.txt", payload)


def test_decode_rejects_invalid_utf8():
    with pytest.raises(ValueError, match="UTF-8"):
        decode_transcript_upload("meeting.txt", b"\xff\xfe")


def test_vtt_retains_timestamps_speakers_and_multiline_text():
    vtt = """WEBVTT

NOTE generated by Teams
This note is ignored

cue-1
00:00:01.000 --> 00:00:05.000 position:10% align:start
<v Sarah>Welcome &amp; thanks
for joining.</v>

STYLE
::cue { color: white }

00:00:06.000 --> 00:00:08.500
<v John>Happy to be here.</v>
"""

    assert convert_vtt_to_text(vtt) == (
        "[00:00:01.000 --> 00:00:05.000] Sarah: Welcome & thanks for joining.\n"
        "[00:00:06.000 --> 00:00:08.500] John: Happy to be here."
    )


def test_vtt_preserves_existing_speaker_prefix():
    vtt = """WEBVTT

00:01.000 --> 00:03.000
Sarah: Existing speaker label
"""

    assert convert_vtt_to_text(vtt) == (
        "[00:01.000 --> 00:03.000] Sarah: Existing speaker label"
    )


def test_vtt_rejects_content_without_cues():
    with pytest.raises(ValueError, match="no transcript cues"):
        convert_vtt_to_text("WEBVTT\n\nNOTE no spoken content")
